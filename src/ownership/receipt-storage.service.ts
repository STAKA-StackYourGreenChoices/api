import {
  BadRequestException,
  Injectable,
  NotFoundException,
} from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { randomUUID } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { mkdir, stat, unlink, writeFile } from 'node:fs/promises';
import { isAbsolute, join, relative, resolve } from 'node:path';

export const MAX_RECEIPT_BYTES = 5 * 1024 * 1024;

/** Accepted receipt types, identified by their first bytes rather than by name or browser-sent type. */
const SIGNATURES: {
  mime: string;
  ext: string;
  test: (b: Buffer) => boolean;
}[] = [
  {
    mime: 'image/jpeg',
    ext: 'jpg',
    test: (b) => b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff,
  },
  {
    mime: 'image/png',
    ext: 'png',
    test: (b) =>
      b
        .subarray(0, 8)
        .equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])),
  },
  {
    mime: 'image/webp',
    ext: 'webp',
    test: (b) =>
      b.subarray(0, 4).toString('ascii') === 'RIFF' &&
      b.subarray(8, 12).toString('ascii') === 'WEBP',
  },
  {
    mime: 'application/pdf',
    ext: 'pdf',
    test: (b) => b.subarray(0, 5).toString('ascii') === '%PDF-',
  },
];

export function detectReceiptType(buffer: Buffer) {
  return SIGNATURES.find((signature) => signature.test(buffer));
}

/**
 * Stores receipt uploads on local disk under UPLOADS_DIR (default ./uploads).
 * Files get random names, are never served statically, and can only be read
 * back through the claims endpoints after an ownership check.
 */
@Injectable()
export class ReceiptStorageService {
  private readonly root: string;

  constructor(config: ConfigService) {
    this.root = resolve(config.get<string>('UPLOADS_DIR') ?? 'uploads');
  }

  async save(buffer: Buffer): Promise<{ path: string; mimeType: string }> {
    if (buffer.length === 0) {
      throw new BadRequestException('The file is empty');
    }
    if (buffer.length > MAX_RECEIPT_BYTES) {
      throw new BadRequestException('Receipts must be 5 MB or smaller');
    }
    const type = detectReceiptType(buffer);
    if (!type) {
      throw new BadRequestException(
        'Upload a photo (JPG, PNG or WebP) or a PDF of the receipt',
      );
    }

    const path = join('receipts', `${randomUUID()}.${type.ext}`);
    await mkdir(join(this.root, 'receipts'), { recursive: true });
    await writeFile(join(this.root, path), buffer, { flag: 'wx', mode: 0o600 });
    return { path, mimeType: type.mime };
  }

  async open(path: string) {
    const full = this.resolveInside(path);
    try {
      const info = await stat(full);
      return { stream: createReadStream(full), size: info.size };
    } catch {
      throw new NotFoundException('The receipt file is missing');
    }
  }

  /** Best effort: used to clean up after a failed save. */
  async remove(path: string): Promise<void> {
    await unlink(this.resolveInside(path)).catch(() => undefined);
  }

  /** Stored paths are generated by us, but never trust a path to stay inside the folder. */
  private resolveInside(path: string) {
    const full = resolve(this.root, path);
    const rel = relative(this.root, full);
    if (rel.startsWith('..') || isAbsolute(rel)) {
      throw new NotFoundException('The receipt file is missing');
    }
    return full;
  }
}
